#!/usr/bin/env python3
"""Turn a few characters of a TrueType font into an LVGL 9 font (C source).

Why this exists: the official converter (lv_font_conv) needs npm, which this Pi
does not have. The board only needs a handful of large letters, so this small
script renders them with Pillow and writes the same 4-bit format that
lv_font_conv produces (plain, uncompressed bitmaps).

Usage:
    python3 scripts/make_lvgl_font.py FONT.ttf SIZE_PX CHARS NAME OUT.c
    (CHARS = the characters to include, or the word ascii for all printable ASCII)
Example (the "A" in the middle of the board's reactor ring):
    python3 scripts/make_lvgl_font.py /usr/share/fonts/truetype/hack/Hack-Bold.ttf \
        34 A font_hack_bold_34 esp32-hud/firmware/main/font_hack_bold_34.c
"""
import sys
from PIL import Image, ImageDraw, ImageFont


def render(font, ch):
    """Return (4-bit pixel list, box_w, box_h, ofs_x, ofs_y, advance_px) for one char."""
    ascent, _ = font.getmetrics()
    left, top, right, bottom = font.getbbox(ch)
    w, h = max(right - left, 1), max(bottom - top, 1)
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
    px = [(v + 8) >> 4 if v < 248 else 15 for v in img.tobytes()]   # 8-bit -> 4-bit alpha
    adv = font.getlength(ch)
    # LVGL measures ofs_y from the baseline up to the bottom of the glyph box
    ofs_y = ascent - bottom
    return px, w, h, left, ofs_y, adv


def pack4(px):
    """LVGL packs 4-bit pixels as one continuous bit stream (rows are NOT byte aligned)."""
    if len(px) % 2:
        px = px + [0]
    return [(px[i] << 4) | px[i + 1] for i in range(0, len(px), 2)]


def main():
    ttf, size, chars, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
    if chars == "ascii":                       # all printable ASCII, space to '~'
        chars = "".join(chr(c) for c in range(0x20, 0x7F))
    chars = sorted(set(chars), key=ord)
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()

    bitmap, glyphs = [], []
    for ch in chars:
        px, w, h, ox, oy, adv = render(font, ch)
        glyphs.append((len(bitmap), round(adv * 16), w, h, ox, oy, ch))
        bitmap += pack4(px)

    codes = [ord(c) for c in chars]
    lines = [
        f"/* {name}: generated by scripts/make_lvgl_font.py from {ttf.split('/')[-1]} at {size}px.",
        f" * Characters: {''.join(chars) if len(chars) < 20 else 'printable ASCII'!r}. Anything else falls back to lv_font_unscii_16.",
        " * Do not edit by hand, re-run the script instead. */",
        '#include "lvgl.h"',
        "",
        "static const uint8_t glyph_bitmap[] = {",
    ]
    for i in range(0, len(bitmap), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) + ",")
    lines += [
        "};",
        "",
        "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {",
        "    { .bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0 },  /* id 0 is reserved */",
    ]
    for bi, adv, w, h, ox, oy, ch in glyphs:
        lines.append(f"    {{ .bitmap_index = {bi}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                     f".ofs_x = {ox}, .ofs_y = {oy} }},  /* '{ch}' */")
    lines += [
        "};",
        "",
        f"static const uint16_t unicode_list[] = {{ {', '.join(str(c - codes[0]) for c in codes)} }};",
        "",
        "static const lv_font_fmt_txt_cmap_t cmaps[] = {",
        f"    {{ .range_start = {codes[0]}, .range_length = {codes[-1] - codes[0] + 1}, .glyph_id_start = 1,",
        f"      .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(codes)},",
        "      .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY },",
        "};",
        "",
        "static const lv_font_fmt_txt_dsc_t font_dsc = {",
        "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,",
        "    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0,",
        "    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,",
        "};",
        "",
        f"const lv_font_t {name} = {{",
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
        "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        f"    .line_height = {ascent + descent},",
        f"    .base_line = {descent},",
        "    .subpx = LV_FONT_SUBPX_NONE,",
        "    .underline_position = -3,",
        "    .underline_thickness = 2,",
        "    .dsc = &font_dsc,",
        "    .fallback = &lv_font_unscii_16,",
        "};",
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {len(chars)} glyphs, {len(bitmap)} bytes of bitmap")


if __name__ == "__main__":
    main()
